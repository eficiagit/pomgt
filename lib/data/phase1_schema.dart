enum DbFieldKind {
  textValue,
  numberValue,
  integerValue,
  booleanValue,
  dateValue,
  dateTimeValue,
  jsonValue,
  enumValue,
  reference,
}

class DbFieldSpec {
  const DbFieldSpec({
    required this.name,
    required this.label,
    required this.kind,
    this.required = false,
    this.hidden = false,
    this.readOnly = false,
    this.referenceTable,
    this.referenceColumn = 'id',
    this.enumValues = const [],
    this.help,
    this.defaultValue,
  });
  final String name;
  final String label;
  final DbFieldKind kind;
  final bool required;
  final bool hidden;
  final bool readOnly;
  final String? referenceTable;
  final String referenceColumn;
  final List<String> enumValues;
  final String? help;
  final dynamic defaultValue;
}

class DbTableSpec {
  const DbTableSpec({
    required this.table,
    required this.title,
    required this.description,
    required this.fields,
